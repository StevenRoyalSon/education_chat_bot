-- ============================================================
-- Education Chatbot Database Schema for Supabase
-- ============================================================
-- This SQL file creates all tables and security policies needed
-- for the Grade 1-5 Education Chatbot
-- ============================================================

-- Enable the UUID extension for generating unique IDs
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================================
-- 1. USERS TABLE
-- Stores user registration information
-- ============================================================
CREATE TABLE IF NOT EXISTS users (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Add comments to explain the table
COMMENT ON TABLE users IS 'Stores user registration details for the education chatbot';
COMMENT ON COLUMN users.id IS 'Unique identifier for each user';
COMMENT ON COLUMN users.name IS 'Full name of the user';
COMMENT ON COLUMN users.email IS 'User email address (must be unique)';
COMMENT ON COLUMN users.password IS 'Hashed password for authentication';
COMMENT ON COLUMN users.created_at IS 'Timestamp when user was created';

-- ============================================================
-- 2. CHAT HISTORY TABLE
-- Stores conversation history for each user
-- ============================================================
CREATE TABLE IF NOT EXISTS chat_history (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_question TEXT NOT NULL,
    ai_response TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Add comments to explain the table
COMMENT ON TABLE chat_history IS 'Stores conversation history between users and the AI';
COMMENT ON COLUMN chat_history.id IS 'Unique identifier for each message';
COMMENT ON COLUMN chat_history.user_id IS 'Foreign key to users table';
COMMENT ON COLUMN chat_history.user_question IS 'The question asked by the user';
COMMENT ON COLUMN chat_history.ai_response IS 'The response generated by the AI';
COMMENT ON COLUMN chat_history.created_at IS 'Timestamp when the message was created';

-- ============================================================
-- 3. DOCUMENT EMBEDDINGS TABLE
-- Stores document chunks and their embeddings for RAG
-- ============================================================
CREATE TABLE IF NOT EXISTS document_embeddings (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    document_name VARCHAR(255) NOT NULL,
    grade VARCHAR(50) NOT NULL,
    subject VARCHAR(100) NOT NULL,
    chunk_text TEXT NOT NULL,
    embedding VECTOR(1536),  -- OpenAI embeddings are 1536 dimensions
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Add comments to explain the table
COMMENT ON TABLE document_embeddings IS 'Stores document chunks and their embeddings for RAG';
COMMENT ON COLUMN document_embeddings.id IS 'Unique identifier for each chunk';
COMMENT ON COLUMN document_embeddings.document_name IS 'Name of the source document';
COMMENT ON COLUMN document_embeddings.grade IS 'Grade level (Grade 1-5)';
COMMENT ON COLUMN document_embeddings.subject IS 'Subject (Math, English, EVS)';
COMMENT ON COLUMN document_embeddings.chunk_text IS 'The text content of the chunk';
COMMENT ON COLUMN document_embeddings.embedding IS 'Vector embedding for similarity search';
COMMENT ON COLUMN document_embeddings.created_at IS 'Timestamp when the chunk was created';

-- ============================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- These policies ensure users can only access their own data
-- ============================================================

-- Enable Row Level Security on all tables
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_embeddings ENABLE ROW LEVEL SECURITY;

-- ============================================================
-- USERS TABLE SECURITY POLICIES
-- ============================================================

-- Allow anyone to insert new users (for signup)
CREATE POLICY "Allow public signup" ON users
    FOR INSERT
    WITH CHECK (true);

-- Allow users to read their own data based on email
CREATE POLICY "Users can read own data" ON users
    FOR SELECT
    USING (email = current_setting('app.current_user_email', true));

-- ============================================================
-- CHAT HISTORY TABLE SECURITY POLICIES
-- ============================================================

-- Allow users to insert their own chat messages
CREATE POLICY "Users can insert own messages" ON chat_history
    FOR INSERT
    WITH CHECK (
        user_id = (
            SELECT id FROM users
            WHERE email = current_setting('app.current_user_email', true)
        )
    );

-- Allow users to read only their own chat history
CREATE POLICY "Users can read own history" ON chat_history
    FOR SELECT
    USING (
        user_id = (
            SELECT id FROM users
            WHERE email = current_setting('app.current_user_email', true)
        )
    );

-- Allow users to delete only their own chat messages
CREATE POLICY "Users can delete own messages" ON chat_history
    FOR DELETE
    USING (
        user_id = (
            SELECT id FROM users
            WHERE email = current_setting('app.current_user_email', true)
        )
    );

-- ============================================================
-- DOCUMENT EMBEDDINGS TABLE SECURITY POLICIES
-- ============================================================

-- Allow all authenticated users to read document embeddings
-- (needed for RAG to work)
CREATE POLICY "Allow read access to embeddings" ON document_embeddings
    FOR SELECT
    USING (true);

-- ============================================================
-- INDEXES FOR BETTER PERFORMANCE
-- ============================================================

-- Index on users email for faster login lookups
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);

-- Index on chat_history user_id for faster user-specific queries
CREATE INDEX IF NOT EXISTS idx_chat_history_user_id ON chat_history(user_id);

-- Index on document_embeddings grade and subject for filtering
CREATE INDEX IF NOT EXISTS idx_document_embeddings_grade ON document_embeddings(grade);
CREATE INDEX IF NOT EXISTS idx_document_embeddings_subject ON document_embeddings(subject);

